/**
 * Generate the user workspace container image build context.
 *
 * The Dockerfile is generated rather than committed so the base image pin, the computerd layer
 * digest, and the pnpm version have exactly one source of truth: the same constants the runtime
 * bootstrap and the registry drift check already read. A hand-written Dockerfile would be a fourth
 * place for those to disagree, and the failure mode of disagreeing is a container that silently
 * falls back to downloading everything again.
 */
import { spawnSync } from 'node:child_process';
import { mkdir, copyFile, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
const CONTEXT_DIRECTORY = new URL('user-workspace-container/.build/', root);

const SHA256_DIGEST = /^sha256:[a-f0-9]{64}$/;

/**
 * Node for the workspace container, pinned with the checksum nodejs.org publishes for exactly
 * this tarball. Must satisfy the `engines.node` range in `template/package.json`; a test pins
 * that relationship so the two cannot drift apart silently.
 */
export const WORKSPACE_NODE_VERSION = '26.7.0';
const WORKSPACE_NODE_SHA256 = 'bd6b6c31e377bad9ad579bed72e5bc11f4c879ac9452ad51d30e646ea3d828df';

export function parseImageInputs({ provisionerSource, toolchainSource, computerSource }) {
  const base = /docker\.io\/cloudflare\/sandbox:[^@'"\s]+@sha256:[a-f0-9]{64}/.exec(provisionerSource)?.[0];
  const computerdDigest = /COMPUTERD_LAYER_DIGEST\s*=\s*'(sha256:[a-f0-9]{64})'/.exec(toolchainSource)?.[1];
  const pnpmVersion = /GENERATED_PROJECT_PNPM_VERSION\s*=\s*'([0-9]+\.[0-9]+\.[0-9]+)'/.exec(computerSource)?.[1];
  const computerdRoot = /COMPUTERD_ROOT\s*=\s*'(\/[^']+)'/.exec(toolchainSource)?.[1];
  const pnpmStore = /CONTAINER_PNPM_STORE_DIR\s*=\s*'(\/[^']+)'/.exec(toolchainSource)?.[1];

  if (!base) {
    throw new Error('Could not find the pinned Cloudflare Sandbox base image in the provisioner.');
  }
  if (!computerdDigest || !SHA256_DIGEST.test(computerdDigest)) {
    throw new Error('Could not find the pinned computerd layer digest in the container toolchain.');
  }
  if (!pnpmVersion) {
    throw new Error('Could not find the pinned generated-project pnpm version.');
  }
  if (!computerdRoot || !pnpmStore) {
    throw new Error('Could not find the container computerd root and pnpm store paths.');
  }
  return { base, computerdDigest, pnpmVersion, computerdRoot, pnpmStore };
}

export function renderDockerfile({ base, computerdDigest, pnpmVersion, computerdRoot, pnpmStore }) {
  const nodeRoot = '/opt/ghostbuild/node';
  const layerSha = computerdDigest.slice('sha256:'.length);
  return `# Generated by scripts/build-user-workspace-image.mjs. Do not edit.
FROM ${base}

LABEL org.opencontainers.image.title="Ghostbuild user workspace"
LABEL org.opencontainers.image.description="Cloudflare Sandbox with the Ghostbuild workspace toolchain and a pre-warmed pnpm store."
LABEL org.opencontainers.image.source="https://github.com/ferdousbhai/ghost-build"
LABEL org.opencontainers.image.licenses="Apache-2.0"
LABEL org.opencontainers.image.base.name="${base}"

# The base image ships Node 22, while generated projects declare engines.node >= 26 (#135). That
# is a warning right up until a dependency actually needs 26, and then it is a hard failure inside
# a container the user cannot upgrade.
#
# Installed into its own prefix and put first on PATH, rather than unpacked over /usr/local.
# Extracting Node over an existing Node merges two npm trees and leaves stale files behind, and
# the resulting npm dies with "Class extends value undefined is not a constructor". A separate
# prefix also leaves the base image's own Node 22 intact for anything that expects it.
#
# libatomic1 is not in the base image and Node 26's official linux-x64 build links against it, so
# without it node fails at load time with a missing libatomic.so.1 rather than anything that names
# Node. The tarball is checksum-verified against nodejs.org the way the computerd layer is.
ENV PATH=${nodeRoot}/bin:$PATH
RUN set -eu; \\
    apt-get update -qq; \\
    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends libatomic1; \\
    rm -rf /var/lib/apt/lists/*; \\
    mkdir -p ${nodeRoot}; \\
    curl -fsSL -o /tmp/node.tar.gz 'https://nodejs.org/dist/v${WORKSPACE_NODE_VERSION}/node-v${WORKSPACE_NODE_VERSION}-linux-x64.tar.gz'; \\
    echo '${WORKSPACE_NODE_SHA256}  /tmp/node.tar.gz' | sha256sum -c -; \\
    tar -xzf /tmp/node.tar.gz -C ${nodeRoot} --strip-components=1 \\
      --exclude=CHANGELOG.md --exclude=LICENSE --exclude=README.md; \\
    rm -f /tmp/node.tar.gz; \\
    test "$(node --version)" = 'v${WORKSPACE_NODE_VERSION}'

# pnpm at the exact version generated projects declare, so the runtime toolchain probe
# ("is pnpm present at this version?") is already satisfied on a cold container.
RUN npm install --global pnpm@${pnpmVersion} --ignore-scripts --no-audit --no-fund \\
      --registry=https://registry.npmjs.org/ \\
 && test "$(pnpm --version)" = "${pnpmVersion}"

# Cloudflare's computerd, from the same immutable GHCR layer the runtime bootstrap would fetch.
RUN set -eu; \\
    mkdir -p ${computerdRoot}; \\
    token="$(curl -fsSL 'https://ghcr.io/token?service=ghcr.io&scope=repository:cloudflare/computer-computerd-linux-x64:pull' | jq -er .token)"; \\
    curl -fsSL -H "Authorization: Bearer $token" -o /tmp/computerd-layer.tgz \\
      'https://ghcr.io/v2/cloudflare/computer-computerd-linux-x64/blobs/${computerdDigest}'; \\
    echo '${layerSha}  /tmp/computerd-layer.tgz' | sha256sum -c -; \\
    tar -xzf /tmp/computerd-layer.tgz -C ${computerdRoot}; \\
    rm -f /tmp/computerd-layer.tgz; \\
    chmod 0755 ${computerdRoot}/usr/local/bin/computerd; \\
    test -x ${computerdRoot}/usr/local/bin/computerd

# The runtime passes --store-dir explicitly, so this is belt-and-braces for any other pnpm
# invocation inside the container (npm_config_* is pnpm's documented environment config form).
ENV npm_config_store_dir=${pnpmStore}

# pnpm otherwise runs an implicit "are node_modules in sync with the lockfile" install before any
# \`pnpm run <script>\`. Inside /home/project that mount is the durable VFS, so the implicit install
# writes a full dependency tree through FUSE into Durable Object storage and the workspace exceeds
# its isolate memory limit permanently — cleanup needs the DO to survive long enough to run, and it
# no longer can (#137). Disabling it at the image level puts it out of reach of anything the model
# can edit in the project. The isolated validation, preview, and deployment roots all run an
# explicit \`pnpm install --frozen-lockfile\` first, so nothing depended on the implicit one.
ENV npm_config_verify_deps_before_run=false

# Warm that store from the template lockfile. This is a cache, not a constraint: a project whose
# lockfile has moved on still installs, it just fetches what the store is missing.
#
# --ignore-scripts because a store warm has no business running dependency install scripts: the
# store holds tarballs, and scripts only take effect when a package is linked into a node_modules.
# Without it the image build executes third-party postinstall code that the runtime install
# (--ignore-scripts=true) deliberately refuses to run.
COPY template-lockfile/ /tmp/ghostbuild-template-fetch/
RUN cd /tmp/ghostbuild-template-fetch \\
 && pnpm fetch --ignore-scripts --store-dir ${pnpmStore} --registry=https://registry.npmjs.org/ \\
 && rm -rf /tmp/ghostbuild-template-fetch /root/.cache/pnpm
`;
}

export async function buildContext() {
  const [provisionerSource, toolchainSource, computerSource] = await Promise.all([
    readFile(new URL('app/lib/.server/cloudflare/user-workspace-runtime-provisioner.ts', root), 'utf8'),
    readFile(new URL('user-workspace-runtime/src/container-toolchain.ts', root), 'utf8'),
    readFile(new URL('ghostbuild-agent/cloudflare-computer.ts', root), 'utf8'),
  ]);
  const inputs = parseImageInputs({ provisionerSource, toolchainSource, computerSource });

  await rm(CONTEXT_DIRECTORY, { recursive: true, force: true });
  await mkdir(new URL('template-lockfile/', CONTEXT_DIRECTORY), { recursive: true });
  for (const file of ['package.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml']) {
    await copyFile(new URL(`template/${file}`, root), new URL(`template-lockfile/${file}`, CONTEXT_DIRECTORY));
  }
  await writeFile(new URL('Dockerfile', CONTEXT_DIRECTORY), renderDockerfile(inputs), 'utf8');
  return { directory: fileURLToPath(CONTEXT_DIRECTORY), ...inputs };
}

/**
 * Where the exported OCI layout lands. This layout is the canonical artifact: `docker save` and
 * any `docker pull`/`push` round trip re-serialize the manifest and change its digest, and the
 * digest is what a provisioned container application pins. Only a buildx OCI export produces
 * compressed blobs whose digests match the manifest that ships with them.
 */
const OCI_LAYOUT_DIRECTORY = fileURLToPath(new URL('user-workspace-container/.build/oci/layout/', root));

function run(command, args) {
  const result = spawnSync(command, args, { stdio: 'inherit' });
  if (result.error) {
    throw result.error;
  }
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} exited with ${result.status}.`);
  }
}

/** Needs the docker-container driver; the default docker driver has no OCI exporter. */
async function exportOciLayout(contextDirectory) {
  const tarball = fileURLToPath(new URL('user-workspace-container/.build/oci/image.tar', root));
  const builder = 'ghostbuild-oci';
  spawnSync('docker', ['buildx', 'create', '--name', builder, '--driver', 'docker-container', '--bootstrap'], {
    stdio: 'ignore',
  });
  await mkdir(OCI_LAYOUT_DIRECTORY, { recursive: true });
  run('docker', [
    'buildx',
    '--builder',
    builder,
    'build',
    '--platform',
    'linux/amd64',
    '--provenance=false',
    '--output',
    `type=oci,dest=${tarball}`,
    contextDirectory,
  ]);
  run('tar', ['-xf', tarball, '-C', OCI_LAYOUT_DIRECTORY]);
  await rm(tarball, { force: true });
  return OCI_LAYOUT_DIRECTORY;
}

async function main() {
  const context = await buildContext();
  console.log(`Build context: ${context.directory}`);
  console.log(`Base image:    ${context.base}`);
  console.log(`computerd:     ${context.computerdDigest}`);
  console.log(`pnpm:          ${context.pnpmVersion}`);

  if (process.argv.includes('--oci')) {
    console.log(`\nOCI layout: ${await exportOciLayout(context.directory)}`);
    console.log(
      'Mirror it with: node scripts/publish-workspace-image-blobs.mjs user-workspace-container/.build/oci/layout',
    );
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
