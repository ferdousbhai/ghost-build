import { describe, expect, it } from 'vitest';
import { WORK_DIR } from 'ghostbuild-agent/constants';
import { IGNORED_PATHS, IGNORED_RELATIVE_PATHS } from './constants';

describe('ignored file paths', () => {
  it('keeps absolute ignored paths aligned with relative paths', () => {
    expect(IGNORED_RELATIVE_PATHS).toEqual([
      'dist',
      'node_modules',
      '.output',
      '.tanstack',
      '.wrangler',
      '.git',
      '.git/**',
      '**/.git',
      '**/.git/**',
      '.npmrc',
      '**/.npmrc',
      '.netrc',
      '**/.netrc',
      '_netrc',
      '**/_netrc',
      '.git-credentials',
      '**/.git-credentials',
      '.pypirc',
      '**/.pypirc',
      '.yarnrc',
      '**/.yarnrc',
      '.yarnrc.yml',
      '**/.yarnrc.yml',
      '.pnpmfile.cjs',
      '**/.pnpmfile.cjs',
      '.pnpmfile.js',
      '**/.pnpmfile.js',
      '.env',
      '.env.*',
      '**/.env',
      '**/.env.*',
      '.envrc',
      '**/.envrc',
      '.dev.vars',
      '.dev.vars.*',
      '**/.dev.vars',
      '**/.dev.vars.*',
    ]);
    expect(IGNORED_PATHS).toEqual([
      `${WORK_DIR}/dist/`,
      `${WORK_DIR}/node_modules/`,
      `${WORK_DIR}/.output/`,
      `${WORK_DIR}/.tanstack/`,
      `${WORK_DIR}/.wrangler/`,
      `${WORK_DIR}/.git/`,
      `${WORK_DIR}/.git`,
      `${WORK_DIR}/.npmrc`,
      `${WORK_DIR}/.netrc`,
      `${WORK_DIR}/_netrc`,
      `${WORK_DIR}/.git-credentials`,
      `${WORK_DIR}/.pypirc`,
      `${WORK_DIR}/.yarnrc`,
      `${WORK_DIR}/.yarnrc.yml`,
      `${WORK_DIR}/.pnpmfile.cjs`,
      `${WORK_DIR}/.pnpmfile.js`,
      `${WORK_DIR}/.env`,
      `${WORK_DIR}/.env.`,
      `${WORK_DIR}/.env.local`,
      `${WORK_DIR}/.envrc`,
      `${WORK_DIR}/.dev.vars`,
      `${WORK_DIR}/.dev.vars.`,
    ]);
  });
});
